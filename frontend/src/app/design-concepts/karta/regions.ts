// Общие правила: область эмитента по адресу регистрации (карта «Карта» и вариант «Сеть»).
import type { RegionId } from "./kgz-map";

// Область по адресу регистрации. Порядок важен: город Ош раньше Ошской области, Бишкек раньше Чуйской.
// Граница слова — (?!\p{L}) с флагом u: обычный  в JS не работает с кириллицей.
const regionRules: [RegionId, RegExp][] = [
  ["osh", /(^|[\s,.])г\.?\s*ош(?!\p{L})|город ош/u],
  ["bishkek", /бишкек|^720\d{3}/u],
  ["issyk", /иссык|ысык-к[уө]л|каракол|балыкчы|чолпон|тюп|тону|жети-?огуз|кызыл-суу|ак-суй|теплоключ/u],
  ["naryn", /нарын|ат-баш|кочкорск|кочкор(?![\p{L}-])|жумгал|ак-талаа/u],
  ["talas", /талас|кара-буур|бакай-ата/u],
  ["jalal", /джалал|жалал|кара-к[уө]л|таш-к[уө]м[уы]р|кочкор-ата|майлуу|токтогул|ноокен|сузак|базар-коргон|аксы|ала-бука|чаткал/u],
  ["batken", /баткен|кызыл-кия|сулюкта|кадамжай|лейлек/u],
  ["osh", /ошск|узген|[өо]згон|кара-суу|ноокат|алай|кара-кулджа|араван/u],
  ["chuy", /чуй|кант(?!\p{L})|токмок|кара-?балт|сокулук|аламуд|аламед|ысык-ат|московск|жайыл|панфилов|кемин|беловод|шопоков|каинд|люксембург/u],
];

export function regionOf(address: string): RegionId | null {
  const a = address.toLowerCase();
  return regionRules.find(([, rule]) => rule.test(a))?.[0] ?? null;
}

// Название без формы собственности, кавычек и дефисов: «ОАО Каинды Кант» и «ОАО Каинды-Кант» — одна компания.
export const short = (name: string) =>
  name
    .replace(/^(ОАО|ЗАО|ОсОО|АООТ|АО)\s+/, "")
    .replace(/[«»"]/g, "")
    .replace(/[-\s]+/g, " ")
    .trim();
