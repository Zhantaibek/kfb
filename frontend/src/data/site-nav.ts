export const siteFooterColumns = siteNav.slice(0, 3).map((group) => ({
  title: group.label,
  links: flattenLinks(group.items).slice(0, 4),
}));

function flattenLinks(items: SiteLink[]): [string, string][] {
  const out: [string, string][] = [];
  for (const item of items) {
    if (item.children?.length) {
      for (const child of item.children) out.push([child.href, child.label]);
    } else {
      out.push([item.href, item.label]);
    }
  }
  return out;
}

