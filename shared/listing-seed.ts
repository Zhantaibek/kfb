export type ListingSeed = Omit<CmsListingEntry, "id" | "updatedAt">;

/** Строки списка и карточки листинга совпадают по коду бумаги — склеиваем их в одну запись. */
export function buildListingSeed(): ListingSeed[] {
  const details = new Map(listingDetails.map((item) => [item.code, item]));
  const categoryByTitle = new Map(
    Object.entries(listingCategoryTitles).map(([id, title]) => [title, id as ListingCategoryId]),
  );
  return listingRows.flatMap((group) => {
    const category = categoryByTitle.get(group.title) ?? "C";
    return group.rows.map((row, index) => {
      const detail = details.get(row.code);
      return {
        code: row.code,
        category,
        order: index + 1,
        name: row.name,
        issuerSlug: row.slug || detail?.slug || "",
        security: row.security || detail?.security || "",
        price: row.price,
        cap: row.cap,
        count: row.count,
        doc: row.doc,
        symbols: detail?.symbols ?? "",
        industry: detail?.industry ?? "",
        activity: detail?.activity ?? "",
        listedAt: detail?.listedAt ?? "",
        auditor: detail?.auditor ?? "",
        registrar: detail?.registrar ?? "",
        marketMaker: detail?.marketMaker ?? "",
        documents: detail?.documents ?? [],
      };
    });
  });
}

export function listingSeedRows(updatedAt: string): CmsListingEntry[] {
  return buildListingSeed().map((item) => ({ ...item, id: `listing-${item.code}`, updatedAt }));
}
